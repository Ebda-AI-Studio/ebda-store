const DISPOSABLE_SET: ReadonlySet<string> = new Set(
  DISPOSABLE_EMAIL_DOMAINS.map(d => d.trim().toLowerCase())
);

/** The lowercase domain part of an address, or `null` when it has no usable `@domain`. */
export function emailDomain(email: string | null | undefined): string | null {
  if (typeof email !== 'string') return null;
  const at = email.lastIndexOf('@');
  if (at < 1 || at === email.length - 1) return null;
  const domain = email
    .slice(at + 1)
    .trim()
    .toLowerCase()
    .replace(/\.+$/, '');
  return domain.length > 0 ? domain : null;
}

/**
 * True when the address's domain — or any PARENT domain of it — is a listed
 * disposable service. Case-insensitive; `a@Sub.Mailinator.COM` is blocked. A
 * sibling that merely ENDS with a listed name (`notmailinator.org.example`,
 * `evilmailinator.com`) is a different domain and is not matched.
 */
export function isDisposableEmail(email: string | null | undefined): boolean {
  const domain = emailDomain(email);
  if (!domain) return false;
  const labels = domain.split('.');
  for (let i = 0; i < labels.length - 1; i++) {
    if (DISPOSABLE_SET.has(labels.slice(i).join('.'))) return true;
  }
  return false;
}
