#!/usr/bin/env node
// Regenerates packages/database/src/tenant-guard-schema.generated.ts from the Prisma client's
// DMMF. The tenant guard cannot read `Prisma.dmmf` at runtime: it throws on Workers (edge
// runtimes). Run after any schema.prisma change, once `prisma generate` has run:
//   npm run gen:tenant-guard-schema -w packages/database          # write
//   npm run gen:tenant-guard-schema -w packages/database -- --check   # fail if stale
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const require = createRequire(import.meta.url);
const { Prisma } = require('@prisma/client');
const OUT = fileURLToPath(new URL('../src/tenant-guard-schema.generated.ts', import.meta.url));

export function render(models) {
  const rows = models.map(m => {
    const relations = {};
    for (const f of m.fields) if (f.kind === 'object') relations[f.name] = f.type;
    return {
      name: m.name,
      table: m.dbName ?? m.name,
      storeId: m.fields.some(f => f.name === 'storeId' && f.kind === 'scalar'),
      relations,
    };
  });
  return `// GENERATED by packages/database/scripts/gen-tenant-guard-schema.mjs - do not edit.
// A snapshot of the Prisma DMMF the tenant guard needs, because \`Prisma.dmmf\` throws on Workers.
// tests/unit/tenant-guard-schema-snapshot.test.ts fails when this drifts from the generated client.

export interface TenantGuardModel {
  name: string;
  /** database table name (\`@@map\`), else the model name */
  table: string;
  /** has a \`storeId\` scalar column */
  storeId: boolean;
  /** relation field -> target model */
  relations: Readonly<Record<string, string>>;
}

export const TENANT_GUARD_SCHEMA: readonly TenantGuardModel[] = ${JSON.stringify(rows, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const cfg = (await prettier.resolveConfig(OUT)) ?? {};
  const next = await prettier.format(render(Prisma.dmmf.datamodel.models), {
    ...cfg,
    parser: 'typescript',
  });
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(OUT, 'utf8');
    } catch {}
    if (cur !== next) {
      console.error(
        'tenant-guard-schema.generated.ts is stale: run npm run gen:tenant-guard-schema -w packages/database'
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    console.log('wrote', OUT);
  }
}
