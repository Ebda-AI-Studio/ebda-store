// Pre-renders each BARKOD shape's silhouette to a 1-bit mask at the email PNG
// width (720px) so the API Worker needs no SVG engine at runtime.
// Usage: node scripts/gen-barcode-masks.mjs > apps/api/src/lib/barcode-png/shape-masks.generated.ts
// Shape drawings: BARKOD studio, used with permission (docs/third-party/barkod-studio.md).
import { Resvg } from '@resvg/resvg-js';
import { deflateSync } from 'node:zlib';
import { readFileSync } from 'node:fs';

const src = readFileSync(
  new URL('../packages/shared/src/barcode/shapes.generated.ts', import.meta.url),
  'utf8'
);
const json = src.slice(src.indexOf('= {') + 2, src.lastIndexOf('};') + 1);
const DATA = JSON.parse(json);
const PAD = 12;
const WIDTH = 720;
const out = {};
for (const [id, { w, h, d }] of Object.entries(DATA)) {
  const vw = w + PAD * 2;
  const vh = h + PAD * 2;
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vw} ${vh}"><rect width="${vw}" height="${vh}" fill="black"/>` +
    d
      .map(
        p =>
          `<path d="${p}" fill="white" fill-rule="evenodd" transform="translate(${PAD},${PAD})"/>`
      )
      .join('') +
    `</svg>`;
  const r = new Resvg(svg, { fitTo: { mode: 'width', value: WIDTH } }).render();
  const W = r.width;
  const H = r.height;
  const px = r.pixels; // RGBA
  const rowBytes = Math.ceil(W / 8);
  const bits = Buffer.alloc(rowBytes * H);
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++)
      if (px[(y * W + x) * 4] > 127) bits[y * rowBytes + (x >> 3)] |= 0x80 >> (x & 7);
  out[id] = { w: W, h: H, z: deflateSync(bits, { level: 9 }).toString('base64') };
}
console.log(`// GENERATED by scripts/gen-barcode-masks.mjs - do not edit. 1-bit silhouettes (MSB first, rows padded to bytes),
// zlib-deflated, base64. Shape drawings (c) BARKOD studio, used with the owner's permission.
export const SHAPE_MASKS: Record<string, { w: number; h: number; z: string }> = ${JSON.stringify(out)};`);
