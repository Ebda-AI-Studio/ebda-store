#!/usr/bin/env node
/**
 * SEO-5 (P14): self-host the Google Fonts the storefront "looks" paint, so no storefront page makes a
 * render-blocking request to fonts.googleapis.com / fonts.gstatic.com.
 *
 * Reads LOOK_FONT_SPECS (packages/shared/src/looks/fonts.ts, the single list of loadable families),
 * asks the Google Fonts css2 API with a modern Chrome UA (woff2, unicode-range split), keeps the
 * latin / latin-ext / arabic subsets only (Egypt-first; a glyph outside them falls back to the stack),
 * downloads each woff2 once into apps/web/public/fonts/look/ and writes the @font-face rules to
 * apps/web/src/lib/look-font-faces.generated.ts. File names are Google's content hashes, so
 * /fonts/look/* is served `immutable` (apps/web/public/_headers).
 *
 * Run: node scripts/fonts/self-host-look-fonts.mjs   (needs network; output is committed)
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'apps/web/public/fonts/look');
const genFile = join(root, 'apps/web/src/lib/look-font-faces.generated.ts');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext', 'arabic']);

const src = readFileSync(join(root, 'packages/shared/src/looks/fonts.ts'), 'utf8');
const block = src.match(/LOOK_FONT_SPECS: Record<string, string> = \{([\s\S]*?)\n\};/)[1];
const specs = [...block.matchAll(/^\s*(?:'([^']+)'|(\w+)):\s*'([^']*)'/gm)].map(m => [
  m[1] ?? m[2],
  m[3],
]);
if (specs.length < 30) throw new Error(`parsed only ${specs.length} families`);

mkdirSync(outDir, { recursive: true });
const faces = {};
const files = new Map();
for (const [family, spec] of specs) {
  const q = 'family=' + encodeURIComponent(family).replace(/%20/g, '+') + (spec ? ':' + spec : '');
  const css = await (
    await fetch(`https://fonts.googleapis.com/css2?${q}&display=swap`, {
      headers: { 'user-agent': UA },
    })
  ).text();
  if (!css.includes('@font-face')) throw new Error(`no css for ${family}`);
  const rules = [];
  for (const m of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
    if (!KEEP.has(m[1])) continue;
    const url = m[2].match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/)[1];
    const name = url
      .split('/')
      .pop()
      .replace(/[^\w.-]/g, '_');
    if (!files.has(name)) {
      const dest = join(outDir, name);
      if (!existsSync(dest)) {
        const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
        if (buf.length < 500) throw new Error(`bad font download ${url}`);
        writeFileSync(dest, buf);
      }
      files.set(name, family);
    }
    rules.push({
      subset: m[1],
      css: m[2].replace(/\s+/g, ' ').replace(url, `/fonts/look/${name}`),
      file: name,
    });
  }
  faces[family] = rules;
  console.log(family, rules.length, 'faces');
}

const body =
  `// GENERATED by scripts/fonts/self-host-look-fonts.mjs - do not edit.\n` +
  `// Self-hosted @font-face rules (SEO-5): files live in apps/web/public/fonts/look/.\n` +
  `export type LookFontFace = { subset: 'latin' | 'latin-ext' | 'arabic'; css: string; file: string };\n` +
  `export const LOOK_FONT_FACES: Record<string, LookFontFace[]> = ${JSON.stringify(faces, null, 1)};\n`;
writeFileSync(genFile, body);
console.log(files.size, 'font files,', Object.keys(faces).length, 'families');
