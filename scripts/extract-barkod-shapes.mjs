// One-off provenance tool: reads saved https://barkod.studio/shape/<slug> HTML
// (server-rendered SVG) and emits packages/shared/src/barcode/shapes.generated.ts.
// Usage: node scripts/extract-barkod-shapes.mjs <dir-with-slug.html> > shapes.generated.ts
// Shapes used with the owner's permission - see docs/third-party/barkod-studio.md.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
// our id -> barkod.studio page slug
const MAP = {
  palm: 'palm-tree', horse: 'horse', paw: 'paw-print', burger: 'burger', cat: 'cat',
  ghost: 'ghost', 'angry-shark': 'angry-shark', shark: 'shark', 'gym-dude': 'weightlifter',
  heart: 'heart', dog: 'dog', whale: 'whale', bat: 'bat', pizza: 'pizza', cloud: 'cloud',
  spider: 'spider', 'big-cake': 'birthday-cake', lemon: 'lemon', ring: 'ring',
  diamond: 'diamond', pineapple: 'pineapple', 'french-fries': 'french-fries',
  'hot-dog': 'hot-dog', cookie: 'cookie',
};
const out = {};
for (const [id, slug] of Object.entries(MAP)) {
  const h = readFileSync(join(dir, `${slug}.html`), 'utf8');
  const i = h.indexOf('id="barcode-svg-mobile"');
  const m = /<mask [^>]*>([\s\S]*?)<\/mask>/.exec(h.slice(i));
  if (!m) throw new Error(`no mask: ${slug}`);
  const paths = [...m[1].matchAll(/<path d="([^"]+)"([^>]*)>/g)];
  for (const p of paths) {
    if (!/fill-rule="evenodd"/.test(p[2]) || !/translate\(40, 40\) scale\(1, 1\)/.test(p[2]))
      throw new Error(`unexpected path attrs: ${slug}`);
  }
  const zone = /<rect x="40" y="(\d+)" width="(\d+)" height="45" fill="white"/.exec(m[1]);
  if (!zone) throw new Error(`no bar zone: ${slug}`);
  out[id] = { w: +zone[2], h: +zone[1] + 45 - 40, d: paths.map(p => p[1]) };
}
console.log(`// GENERATED by scripts/extract-barkod-shapes.mjs from barkod.studio (fetched 2026-10-21).
// Shape drawings (c) BARKOD studio, used with the owner's permission - docs/third-party/barkod-studio.md.
// w/h = shape box in its own units (the bottom 45 units are the scan zone); d = outline paths (evenodd).
export const BARKOD_SHAPE_DATA: Record<string, { w: number; h: number; d: readonly string[] }> = ${JSON.stringify(out, null, 1)};`);
