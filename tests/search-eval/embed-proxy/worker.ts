/**
 * LOCAL-ONLY embedding proxy for the search eval (tests/search-eval/run.ts). `wrangler dev` runs it
 * on 127.0.0.1 with the Workers AI `AI` binding, which wrangler proxies to the REAL model on the
 * logged-in account (the Whisky account, 69188202…; never a Force AI account). It lets the eval use
 * real bge-m3 without minting or copying an API token: wrangler's own login authorises the binding.
 * Never deployed. `npm run search:eval -- --real` starts and stops it itself.
 *
 * It spends Workers AI, so it answers only the harness that started it (review M4):
 * - `content-type: application/json` only. A webpage in the developer's browser can send a
 *   "simple" cross-origin POST (text/plain, no custom headers) to 127.0.0.1 without a preflight;
 *   JSON or a custom header forces a CORS preflight, which this Worker never answers.
 * - the `x-eval-secret` header must equal `EVAL_PROXY_SECRET`: random per run, generated by the
 *   harness, handed to wrangler through a 0600 temp `--env-file` (never argv, never committed,
 *   never printed) and deleted when the run ends. No strong secret configured = refuse everything.
 * - `wrangler.jsonc` binds 127.0.0.1 (`dev.ip`).
 * POST {"text": ["...", ...]} → the model's raw output ({ shape, data, pooling }).
 */
import { EVAL_SECRET_HEADER, MIN_SECRET_LENGTH } from './shared';

interface Env {
  AI: { run(model: string, input: { text: string[] }): Promise<unknown> };
  EVAL_PROXY_SECRET?: string;
}

/** Length-independent comparison of two strings (no early exit on the first differing byte). */
function sameSecret(a: string, b: string): boolean {
  const x = new TextEncoder().encode(a);
  const y = new TextEncoder().encode(b);
  let diff = x.length ^ y.length;
  for (let i = 0; i < Math.max(x.length, y.length); i++) diff |= (x[i] ?? 0) ^ (y[i] ?? 0);
  return diff === 0;
}

export default {
  async fetch(req: Request, env: Env): Promise<Response> {
    const secret = env.EVAL_PROXY_SECRET ?? '';
    if (secret.length < MIN_SECRET_LENGTH)
      return new Response('proxy started without EVAL_PROXY_SECRET', { status: 503 });
    if (req.method !== 'POST') return new Response('POST only', { status: 405 });
    const type = (req.headers.get('content-type') ?? '').split(';')[0].trim().toLowerCase();
    if (type !== 'application/json')
      return new Response('content-type must be application/json', { status: 415 });
    if (!sameSecret(req.headers.get(EVAL_SECRET_HEADER) ?? '', secret))
      return new Response('forbidden', { status: 403 });
    const body = (await req.json().catch(() => null)) as { text?: unknown } | null;
    const text = body?.text;
    if (
      !Array.isArray(text) ||
      text.length === 0 ||
      text.length > 100 ||
      text.some(t => typeof t !== 'string')
    )
      return new Response('text must be 1-100 strings', { status: 400 });
    return Response.json(await env.AI.run('@cf/baai/bge-m3', { text: text as string[] }));
  },
};
