/**
 * Printable view of an ISSUED fiscal document, rendered from the immutable
 * payload it was issued with (ruling MONEYB-1) — never from the live order, so
 * a later edit, a refund or a store deletion cannot change what it says.
 * Used for credit notes / refund receipts, and for any document in the tax
 * archive (super-admin), including documents of a deleted store.
 */

export interface RenderableDocument {
  docType: string;
  number: string | null;
  status: string;
  issuedAt: Date | string;
  cancelledAt?: Date | string | null;
  originalNumber?: string | null;
  originalIssuedAt?: Date | string | null;
  currency: string;
  netAmount: number;
  vatAmount: number;
  totalAmount: number;
  vatRateBps: number | null;
  sellerTrn: string | null;
  payload: unknown;
}

/** ETA e-receipt state, read live (never part of the immutable payload). */
export interface RenderableEta {
  status: string;
  uuid: string | null;
  longId: string | null;
  receiptNumber: string | null;
  environment: string;
  /** Verification link; only present once ETA accepted the receipt. */
  qr: string | null;
  /** Pre-rendered SVG of `qr` (generated by us, not user input). */
  qrSvg: string | null;
}

