function esc(v: unknown): string {
  return String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;');
}

export function renderFiscalDocumentHtml(
  doc: RenderableDocument,
  locale: 'ar' | 'en',
  timeZone = 'Africa/Cairo',
  eta: RenderableEta | null = null,
  /** The store's `settings.receiptBarcodeShape` (unset = plain, `off` = none). */
  barcodeShape?: unknown
): string {
  const ar = locale === 'ar';
  const l = ar ? L.ar : L.en;
  // The document's language, not English: Arabic prints «ج.م» (never "EGP") and a sign stays with its number in RTL.
  const money = (n: number) => moneyHtml(n, doc.currency || 'EGP', locale);
  const minus = (n: number) => moneyHtml(n, doc.currency || 'EGP', locale, '\u2212');
  const date = (d: Date | string | null | undefined) =>
    d
      ? new Date(d).toLocaleDateString(intlLocale(locale), {
          year: 'numeric',
          month: 'long',
          day: 'numeric',
          timeZone,
        })
      : '';
  const dateTime = (d: Date | string | null | undefined) =>
    d
      ? new Date(d).toLocaleString(intlLocale(locale), {
          year: 'numeric',
          month: 'long',
          day: 'numeric',
          hour: '2-digit',
          minute: '2-digit',
          timeZone,
        })
      : '';
  const title = (l as unknown as Record<string, string>)[doc.docType] ?? doc.docType;
  type Payload = Partial<SaleDocumentPayload & RefundDocumentPayload> & { orderNumber?: string };
  const p = (doc.payload ?? {}) as Payload;
  const seller = p.seller;
  const version = typeof p.version === 'number' ? p.version : 1;
  const isSaleOrRefund = ['tax_invoice', 'receipt', 'credit_note', 'refund_receipt'].includes(
    doc.docType
  );
  const na = `<span class="muted" data-not-recorded="1">${esc(l.notRecorded)}</span>`;
  const rate = doc.vatRateBps != null ? ` (${doc.vatRateBps / 100}%)` : '';
  const pct = (bps: number | null | undefined) => (bps == null ? '—' : `${bps / 100}%`);
  const row = (label: string, value: string) =>
    value
      ? `<div class="kv"><span class="muted">${esc(label)}</span> <span>${value}</span></div>`
      : '';
  const sellerAddress = seller
    ? [
        seller.address,
        ...(seller.branchAddress
          ? Object.values(seller.branchAddress).filter(v => typeof v === 'string' && v)
          : []),
      ].filter(Boolean)
    : [];

  // Shipping, COD fee and extra charge are totals lines, not purchased items (QA-70): no qty, no unit price.
  const isCharge = (k: string | undefined) => k === 'shipping' || k === 'cod_fee' || k === 'extra';
  const allLines = Array.isArray(p.lines) ? p.lines : [];
  const hasLines = allLines.some(ln => !isCharge(ln.kind));
  const lines = hasLines
    ? allLines
        .filter(ln => !isCharge(ln.kind))
        .map(ln => {
          const v2 = version >= 2;
          const code = [
            ln.internalCode ?? ln.sku,
            ln.etaItemCode && `${l.etaCode}: ${ln.etaItemCode}`,
          ]
            .filter(Boolean)
            .map(c => esc(c))
            .join(' · ');
          return `<tr><td>${esc(ar && ln.descriptionAr ? ln.descriptionAr : ln.description)}${
            code ? `<div class="muted" dir="ltr" data-item-code="1">${code}</div>` : ''
          }${
            (ar ? (ln.priceLabelAr ?? ln.priceLabel) : ln.priceLabel)
              ? `<div class="muted" data-price-label="1">${esc(ar ? (ln.priceLabelAr ?? ln.priceLabel) : ln.priceLabel)}</div>`
              : ''
          }</td>
            <td class="n">${esc(ln.quantity)}</td>
            <td class="n">${ln.unitPrice == null ? '—' : `${ln.listPrice != null ? `<s style="opacity:.6">${money(ln.listPrice)}</s> ` : ''}${money(ln.unitPrice)}`}</td>
            <td class="n">${v2 && ln.vatAmount != null ? esc(pct(ln.vatRateBps)) : na}</td>
            <td class="n">${v2 && ln.vatAmount != null ? money(ln.vatAmount) : na}</td>
            <td class="n">${money(ln.amount)}</td></tr>`;
        })
        .join('')
    : '';
  // QA-70: a charge is a totals-style row (description across the item / qty / unit columns, never a qty and unit price), but it
  // still carries its own VAT rate and amount like every other fiscal line, so the tax archive keeps the shipping VAT.
  const charges = allLines
    .filter(ln => isCharge(ln.kind))
    .map(ln => {
      const v2 = version >= 2;
      const vat = v2 && ln.vatAmount != null;
      return `<tr><td colspan="3">${esc(ar && ln.descriptionAr ? ln.descriptionAr : ln.description)}</td><td class="n">${vat ? esc(pct(ln.vatRateBps)) : na}</td><td class="n">${vat ? money(ln.vatAmount!) : na}</td><td class="n">${money(ln.amount)}</td></tr>`;
    })
    .join('');
  const discounts = Array.isArray(p.discounts)
    ? p.discounts
        .map(
          d =>
            `<tr><td colspan="5">${esc(l.discount)}${d.label ? ` (${esc(d.label)})` : ''}</td><td class="n">${minus(d.amount)}</td></tr>`
        )
        .join('')
    : '';
  const t = (p as Partial<SaleDocumentPayload>).totals;
  const totalRow = (label: string, v: number | undefined | null) =>
    v
      ? `<tr><td colspan="5" class="muted">${esc(label)}</td><td class="n muted">${money(v)}</td></tr>`
      : '';
  const breakdown =
    t && hasLines
      ? [
          totalRow(l.subtotal, t.subtotal),
          totalRow(l.shipping, t.shipping),
          totalRow(l.codFee, t.codFee),
          totalRow(l.extra, t.extra),
        ].join('')
      : '';
  const payMethod = p.paymentMethod ? (l.payMethods[p.paymentMethod] ?? p.paymentMethod) : null;
  const payStatus = p.paymentStatus ? (l.payStatuses[p.paymentStatus] ?? p.paymentStatus) : null;
  const refundSign = doc.docType === 'credit_note' || doc.docType === 'refund_receipt' ? '−' : '';
  const needsEta = isSaleOrRefund;
  const etaBlock = !needsEta
    ? ''
    : eta
      ? `<div class="box" data-eta="1"><strong>${esc(l.eta)}</strong>
${row(l.etaStatus, esc(l.etaStatuses[eta.status] ?? eta.status))}
${row(l.etaUuid, eta.uuid ? `<span dir="ltr" class="mono">${esc(eta.uuid)}</span>` : '')}
${row(l.etaLongId, eta.longId ? `<span dir="ltr" class="mono">${esc(eta.longId)}</span>` : '')}
${row(l.etaReceiptNo, eta.receiptNumber ? `<span dir="ltr">${esc(eta.receiptNumber)}</span>` : '')}
${row(l.etaEnv, esc(eta.environment))}
${eta.qr && /^https:\/\//.test(eta.qr) ? `<div class="qr">${eta.qrSvg ?? ''}<a href="${esc(eta.qr)}" target="_blank" rel="noopener noreferrer">${esc(l.etaVerify)}</a></div>` : ''}</div>`
      : `<div class="box muted" data-eta-none="1">${esc(l.etaNone)}</div>`;

  // QA-69: the order barcode the store configured in /codes (Code 128 of the order number), as the invoice page prints it.
  const barcode = p.orderNumber ? orderBarcodeBlock(p.orderNumber, barcodeShape) : '';

  return `<!DOCTYPE html>
<html lang="${locale}" dir="${ar ? 'rtl' : 'ltr'}">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)} ${esc(doc.number ?? '')}</title>
<style>
  body{font-family:${ar ? '"Noto Sans Arabic",Tahoma,Arial' : '-apple-system,Segoe UI,Roboto,Arial'},sans-serif;color:#0f172a;margin:0;background:#f8fafc}
  .page{max-width:800px;margin:24px auto;background:#fff;border-radius:12px;padding:32px;position:relative}
  h1{font-size:20px;margin:0 0 4px} .muted{color:#475569;font-size:13px}
  table{width:100%;border-collapse:collapse;margin-top:20px;font-size:14px}
  th,td{padding:8px 6px;border-bottom:1px solid #e2e8f0;text-align:start}
  .n{text-align:end;white-space:nowrap} .tot td{font-weight:700}
  .kv{margin:2px 0;font-size:13px} .mono{font-family:ui-monospace,Menlo,monospace;font-size:12px;word-break:break-all}
  .box{margin-top:16px;padding:10px 12px;border:1px solid #e2e8f0;border-radius:8px}
  .grid{display:grid;grid-template-columns:1fr 1fr;gap:16px;margin-top:16px} .qr{margin-top:8px;display:flex;align-items:center;gap:12px} .qr svg{width:96px;height:96px}
  .stamp{position:absolute;top:40%;left:50%;transform:translate(-50%,-50%) rotate(-18deg);font-size:72px;font-weight:900;color:#dc2626;opacity:.08}
  ${ORDER_BARCODE_CSS}
  @media print{body{background:#fff}.page{margin:0;border-radius:0}}
</style></head>
<body><div class="page">
${doc.status === 'cancelled' ? `<div class="stamp">${esc(l.cancelled)}</div>` : ''}
<h1>${esc(title)}</h1>
<div class="muted">${esc(l.number)} <span dir="ltr">${esc(doc.number ?? '—')}</span> · ${esc(l.date)} ${esc(dateTime(doc.issuedAt))}${p.orderNumber ? ` · ${esc(l.order)} <span dir="ltr">${esc(p.orderNumber)}</span>` : ''} · ${esc(l.currency)} <span dir="ltr">${esc(doc.currency)}</span></div>
${doc.originalNumber ? `<div class="muted">${esc(l.original)} <span dir="ltr">${esc(doc.originalNumber)}</span> ${esc(l.originalDate)} ${esc(date(doc.originalIssuedAt ?? p.original?.issuedAt))}</div>` : ''}
<div class="grid">
${
  seller
    ? `<div data-seller="1"><strong>${esc(l.seller)}</strong>
${row('', `${esc(seller.name)}${seller.legalName ? ` · ${esc(seller.legalName)}` : ''}`)}
${row(l.trn, doc.sellerTrn ? `<span dir="ltr">${esc(doc.sellerTrn)}</span>` : '')}
${isSaleOrRefund ? row(l.branchCode, version >= 2 ? (seller.branchCode ? `<span dir="ltr">${esc(seller.branchCode)}</span>` : '') : na) : ''}
${isSaleOrRefund ? row(l.activityCode, version >= 2 ? (seller.activityCode ? `<span dir="ltr">${esc(seller.activityCode)}</span>` : '') : na) : ''}
${version >= 2 && seller.posSerial ? row(l.posSerial, `<span dir="ltr">${esc(seller.posSerial)}</span>`) : ''}
${sellerAddress.length ? row(l.address, sellerAddress.map(esc).join('، ')) : ''}
${seller.phone ? row(l.phone, `<span dir="ltr">${esc(seller.phone)}</span>`) : ''}
${seller.email ? row(l.email, `<span dir="ltr">${esc(seller.email)}</span>`) : ''}</div>`
    : '<div></div>'
}
<div data-buyer="1"><strong>${esc(l.billTo)}</strong>
${p.buyer?.name ? row('', `${esc(p.buyer.name)}${(ar ? p.buyer.addressAr : p.buyer.addressEn)?.length ? ` — ${(ar ? p.buyer.addressAr : p.buyer.addressEn).map(esc).join('، ')}` : ''}`) : ''}
${p.buyerName ? row('', esc(p.buyerName)) : ''}
${!p.buyer?.name && !p.buyerName && isSaleOrRefund ? `<div class="muted">${esc(l.buyerConsumer)}</div>` : ''}
${isSaleOrRefund ? row(l.payment, `${payMethod ? esc(payMethod) : ''}${payStatus ? ` · ${esc(payStatus)}` : version >= 2 ? '' : ` · ${na}`}`) : ''}</div>
</div>
${p.reason ? `<p class="muted">${esc(l.reason)}: ${esc(p.reason)}</p>` : ''}
<table>
  ${lines ? `<thead><tr><th>${esc(l.item)}</th><th class="n">${esc(l.qty)}</th><th class="n">${esc(l.unit)}</th><th class="n">${esc(l.vatRate)}</th><th class="n">${esc(l.vatAmt)}</th><th class="n">${esc(l.lineTotal)}</th></tr></thead>` : ''}
  <tbody>
    ${lines}${discounts}${charges}
    ${breakdown}
    <tr><td colspan="5">${esc(l.net)}</td><td class="n">${money(doc.netAmount)}</td></tr>
    <tr><td colspan="5">${esc(l.vat)}${esc(rate)}</td><td class="n">${money(doc.vatAmount)}</td></tr>
    ${t?.taxIncludedInPrice ? `<tr><td colspan="6" class="muted">${esc(l.priceIncludesVat)}</td></tr>` : ''}
    <tr class="tot"><td colspan="5">${esc(l.total)}</td><td class="n">${refundSign ? minus(doc.totalAmount) : money(doc.totalAmount)}</td></tr>
  </tbody>
</table>
${etaBlock}
${barcode}
</div></body></html>`;
}
