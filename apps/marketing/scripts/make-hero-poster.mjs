// Generates src/lib/hero-poster.ts: the static poster painted (inline, so it is never the
// LCP element) behind the hero before the NileNight canvas starts. Same
// geometry as NileNight.build() at 1600x900 with the Nile at 70% width. Deterministic
// (seeded). Re-run with `npm run poster -w apps/marketing`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const out = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'hero-poster.ts'
);
const W = 1600;
const H = 900;
const LIFT = '#CBA873';
let seed = 11;
const rnd = () => (seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296;
const gauss = () => (rnd() + rnd() + rnd() - 1.5) / 1.5;

const cx = W * 0.7;
const top = H * 0.05;
const deltaY = H * 0.4;
const bottom = H * 1.05;
const r1 = n => Math.round(n);
let dots = '';
for (let i = 0; i < 360; i++) {
  let x;
  let y;
  if (rnd() < 0.46) {
    const t = Math.pow(rnd(), 0.8);
    const a = gauss() * 0.62;
    const r = t * (deltaY - top);
    x = cx + Math.sin(a) * r * 2.1;
    y = deltaY - Math.cos(a) * r * 0.95;
  } else {
    y = deltaY + rnd() * (bottom - deltaY);
    const k = (y - deltaY) / (bottom - deltaY);
    x =
      cx +
      Math.sin(k * 5.2) * W * 0.035 +
      Math.sin(k * 13) * W * 0.008 -
      k * W * 0.03 +
      gauss() * (10 + k * 5);
  }
  const lit = rnd() < 0.025;
  const op = (0.25 + rnd() * 0.6).toFixed(1);
  if (lit) {
    dots += `<circle cx="${r1(x)}" cy="${r1(y)}" r="8" fill="${LIFT}" opacity=".18"/><circle cx="${r1(x)}" cy="${r1(y)}" r="2" fill="${LIFT}"/>`;
  } else {
    dots += `<rect x="${r1(x)}" y="${r1(y)}" width="${rnd() < 0.05 ? 2 : 1}" height="${rnd() < 0.05 ? 2 : 1}" fill-opacity="${op}"/>`;
  }
}
const ax = r1(cx - (deltaY - top) * 0.72);
const ay = r1(top + (deltaY - top) * 0.12);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice"><defs><radialGradient id="g"><stop offset="0" stop-color="#F3F5F4" stop-opacity=".22"/><stop offset="1" stop-color="#F3F5F4" stop-opacity="0"/></radialGradient><linearGradient id="f" x1="0" y1="0" x2="0" y2="1"><stop offset=".55" stop-color="#0A0B0C" stop-opacity="0"/><stop offset="1" stop-color="#0A0B0C" stop-opacity=".85"/></linearGradient></defs><rect width="${W}" height="${H}" fill="#0A0B0C"/><circle cx="${r1(cx)}" cy="${r1(deltaY + 4)}" r="28" fill="url(#g)"/><circle cx="${ax}" cy="${ay}" r="18" fill="url(#g)"/><g fill="#E9EEEC">${dots}</g><rect width="${W}" height="${H}" fill="url(#f)"/></svg>\n`;
const ts = `// Generated by scripts/make-hero-poster.mjs. Do not edit by hand.\nexport const HERO_POSTER_SVG =\n  ${JSON.stringify(svg.trim())};\n`;
writeFileSync(out, ts);
console.log(`wrote ${out} (${ts.length} bytes)`);
