// Turns capture.mjs output into the files the device frames load:
//   public/devices/<id>-<device>-<width>.{avif,webp}   phone 300/600, tablet 420/840, laptop 640/1280
//   public/devices/lamma-story-600.{avif,webp}         the full-page phone strip for the scroll story
//   public/devices/<id>-bar-600.{avif,webp}            the phone's fixed bottom tab bar
//   src/lib/device-shots.ts                            sizes + aspect ratios (generated)
//   node encode.mjs <captureDir>
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.join(here, '..', '..');
const cap = process.argv[2];
const out = path.join(app, 'public', 'devices');
mkdirSync(out, { recursive: true });
const meta = JSON.parse(readFileSync(path.join(cap, 'meta.json'), 'utf8'));
const IDS = ['souq', 'dahab', 'qamar', 'lamma', 'jasmine'];
const WIDTHS = { phone: [300, 600], tablet: [420, 840], laptop: [640, 1280] };
const DPR = { phone: 3, tablet: 2, laptop: 2 };

async function write(img, name) {
  await img
    .clone()
    .avif({ quality: 50, effort: 6 })
    .toFile(path.join(out, `${name}.avif`));
  await img
    .clone()
    .webp({ quality: 72 })
    .toFile(path.join(out, `${name}.webp`));
}

const shots = {};
for (const id of IDS) {
  shots[id] = {};
  for (const dev of Object.keys(WIDTHS)) {
    const src = path.join(cap, `${id}-ar-${dev}.png`);
    const m = await sharp(src).metadata();
    for (const w of WIDTHS[dev]) await write(sharp(src).resize({ width: w }), `${id}-${dev}-${w}`);
    shots[id][dev] = { w: m.width, h: m.height };
  }
  // Bottom tab bar (CSS px * DPR) cropped from the viewport shot.
  const phone = path.join(cap, `${id}-ar-phone.png`);
  const pm = await sharp(phone).metadata();
  const barPx = Math.round((meta[`${id}-ar`]?.bottomBarCss ?? 0) * DPR.phone);
  if (barPx > 0) {
    await write(
      sharp(phone)
        .extract({ left: 0, top: pm.height - barPx, width: pm.width, height: barPx })
        .resize({ width: 600 }),
      `${id}-bar-600`
    );
    shots[id].bar = { w: pm.width, h: barPx };
  }
}
// The scroll-story strip (Lamma): full page, capped so it stays a few hundred KB.
const full = path.join(cap, 'lamma-ar-phone-full.png');
const fm = await sharp(full).metadata();
await write(sharp(full).resize({ width: 600 }), 'lamma-story-600');
const story = { w: fm.width, h: fm.height };

writeFileSync(
  path.join(app, 'src', 'lib', 'device-shots.ts'),
  `// Generated by scripts/storefront-capture/encode.mjs. Do not edit by hand.
// Real apps/web storefront captures (Arabic) of the five example stores at true device
// viewports: phone 390x844 @3x, tablet 820x1180 @2x, laptop 1440x900 @2x.
export const DEVICE_SHOTS = ${JSON.stringify(shots, null, 2)} as const;
export const STORY_STRIP = ${JSON.stringify(story)} as const;
`
);
console.log('encoded', Object.keys(shots).length, 'stores');
