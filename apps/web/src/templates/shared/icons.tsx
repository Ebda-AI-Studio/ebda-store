/** A social link entry with its key, SVG path, and URL. */
export interface SocialLinkEntry {
  key: string;
  icon: string;
  url: string;
}

/**
 * Build a filtered array of social link entries from a `StoreSocials` object.
 * Only entries that have a non-empty URL are included.
 *
 * When `contact.whatsapp` is supplied, a synthetic WhatsApp entry is appended
 * unless `socials.whatsapp` was already set — the merchant's contact phone
 * doubles as a chat link via wa.me. We strip non-digits so saved phone numbers
 * with formatting characters (+, spaces, dashes) still produce a valid URL.
 */
export function getSocialLinks(
  socials: StoreSocials,
  contact?: Pick<StoreContact, 'whatsapp'>
): SocialLinkEntry[] {
  const contactWhatsapp = contact?.whatsapp?.trim();
  const whatsappUrl =
    socials.whatsapp ||
    (contactWhatsapp ? `https://wa.me/${contactWhatsapp.replace(/\D/g, '')}` : undefined);
  return [
    { key: 'instagram', icon: INSTAGRAM_PATH, url: socials.instagram },
    { key: 'facebook', icon: FACEBOOK_PATH, url: socials.facebook },
    { key: 'twitter', icon: TWITTER_PATH, url: socials.twitter },
    { key: 'tiktok', icon: TIKTOK_PATH, url: socials.tiktok },
    { key: 'youtube', icon: YOUTUBE_PATH, url: socials.youtube },
    { key: 'snapchat', icon: SNAPCHAT_PATH, url: socials.snapchat },
    { key: 'whatsapp', icon: WHATSAPP_PATH, url: whatsappUrl },
    { key: 'linkedin', icon: LINKEDIN_PATH, url: socials.linkedin },
    { key: 'pinterest', icon: PINTEREST_PATH, url: socials.pinterest },
    { key: 'telegram', icon: TELEGRAM_PATH, url: socials.telegram },
  ].filter((s): s is SocialLinkEntry => !!s.url);
}
