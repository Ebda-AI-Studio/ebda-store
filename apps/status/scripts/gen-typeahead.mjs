// Bundles the shared live-search client (packages/site-kit/src/client/typeahead.js, MiniSearch inside) into
// src/typeahead-bundle.ts so the status Worker can serve it ITSELF at /assets/typeahead.js: the status page must
// not depend on any other Ebda site being up. Run `npm run gen:typeahead -w apps/status` after editing the client;
// test/typeahead-bundle.test.ts fails while the committed file is stale.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export async function bundled() {
  const r = await build({
    entryPoints: [
      path.join(here, '..', '..', '..', 'packages', 'site-kit', 'src', 'client', 'typeahead.js'),
    ],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2019',
    write: false,
    logLevel: 'error',
  });
  return r.outputFiles[0].text;
}
export const render = js =>
  `// GENERATED by scripts/gen-typeahead.mjs from packages/site-kit/src/client/typeahead.js. Do not edit.\nexport const TYPEAHEAD_JS = ${JSON.stringify(js)};\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(path.join(here, '..', 'src', 'typeahead-bundle.ts'), render(await bundled()));
  console.log('wrote src/typeahead-bundle.ts');
}
